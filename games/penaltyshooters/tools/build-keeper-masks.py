"""Rebuild shared keeper silhouettes from the original atlases (Python + Pillow).

The server uses these same opaque pixels that the browser draws. Sprite origins
and atlas rotation are applied before encoding horizontal runs; transparent
space inside a diving player's bounding box never counts as a save.
"""
import json
from pathlib import Path
from PIL import Image, ImageChops

root = Path(__file__).resolve().parents[1]
assets = root / 'client' / 'assets'
sprites = json.loads((assets / 'sprites.json').read_text())
images = {}
result = {}
for animation in ('Idle', 'MidCatch', 'LowCatch', 'HighCatch', 'MidParade', 'HighParade'):
    body = sprites['goalkeeperNoShirt'][animation]
    masks = []
    for index in range(len(body['frames'])):
        layers = []
        for name in ('goalkeeperNoShirt', 'goalkeeperShirtOrange'):
            f = sprites[name][animation]['frames'][index]
            if f['file'] not in images:
                images[f['file']] = Image.open(assets / f['file']).convert('RGBA')
            w, h = (f['h'], f['w']) if f['rotated'] else (f['w'], f['h'])
            image = images[f['file']].crop((f['x'], f['y'], f['x'] + w, f['y'] + h))
            if f['rotated']:
                image = image.transpose(Image.Transpose.ROTATE_90)
            layers.append((image.getchannel('A'), -round(f['w'] * f['originX']), -round(f['h'] * f['originY'])))
        left = min(x for image, x, y in layers)
        top = min(y for image, x, y in layers)
        right = max(x + image.width for image, x, y in layers)
        bottom = max(y + image.height for image, x, y in layers)
        alpha = Image.new('L', (right - left, bottom - top))
        for image, x, y in layers:
            layer = Image.new('L', alpha.size)
            layer.paste(image, (x - left, y - top))
            alpha = ImageChops.lighter(alpha, layer)
        pixels = alpha.load()
        rows = []
        for y in range(alpha.height):
            row, start = [top + y], None
            for x in range(alpha.width + 1):
                filled = x < alpha.width and pixels[x, y] >= 96
                if filled and start is None:
                    start = left + x
                elif not filled and start is not None:
                    row.extend((start, left + x))
                    start = None
            if len(row) > 1:
                rows.append(row)
        masks.append({'bounds': [left, top, right, bottom], 'rows': rows})
    result[animation] = {'fps': body['fps'], 'frames': masks}
output = root / 'shared' / 'keeper-masks.js'
output.write_text('// Generated by tools/build-keeper-masks.py; body + shirt alpha silhouettes.\nexport default ' + json.dumps(result, separators=(',', ':')) + ';\n')
print(f'{sum(len(a["frames"]) for a in result.values())} keeper masks, {output.stat().st_size} bytes')
